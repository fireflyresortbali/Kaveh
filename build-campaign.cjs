const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const dir=__dirname,file=path.join(dir,'index.html');
let html=fs.readFileSync(file,'utf8').replace(/\r\n/g,'\n');
const levels=JSON.parse(fs.readFileSync(path.join(dir,'campaign-data.json'),'utf8').replace(/^\uFEFF/,''));
if(levels.length!==62||levels.some((l,i)=>l.id!==i+1))throw Error('Campaign must contain all 62 ordered memories.');
const source=fs.readFileSync(path.join(dir,'campaign.js'),'utf8');
new vm.Script(source);
const start='// BEGIN ARIEL CAMPAIGN',end='// END ARIEL CAMPAIGN';
const frame='data:image/webp;base64,'+fs.readFileSync(path.join(dir,'assets/story/ariel-ferdowsi.webp')).toString('base64');
const towerTexture='data:image/webp;base64,'+fs.readFileSync(path.join(dir,'assets/textures/watchtower-adobe.webp')).toString('base64');
const block=start+'\nconst TOWER_TEXTURE='+JSON.stringify(towerTexture)+';\nconst CAMPAIGN_LEVELS='+JSON.stringify(levels)+';\nconst ARIEL_FRAME='+JSON.stringify(frame)+';\n'+source+'\n'+end+'\n';
if(html.includes(start))html=html.slice(0,html.indexOf(start))+block+html.slice(html.indexOf(end)+end.length+1);
else html=html.replace('// ================= loop =================',block+'\n// ================= loop =================');
html=html.replace('setupWorld();initStory();initPortraits();','memory={id:campaign.current,stage:0,targets:[],patrons:[],prayerMultiplier:1};setupWorld();initStory();initPortraits();');
html=html.replace(/(?:memory=\{id:campaign.current,stage:0,targets:\[\],patrons:\[\],prayerMultiplier:1\};)+/g,'memory={id:campaign.current,stage:0,targets:[],patrons:[],prayerMultiplier:1};');
html=html.replace("story(INTRO,()=>msg('Drag from a unit to move it, or tap it and then tap the ground.'));",'openCampaign();');
html=html.replaceAll("Kaveh's Banner",'Ariel of the Shahnameh').replaceAll('Favor','Glory');
html=html.replace('The Shahnameh · Chapter I','The Shahnameh · 62 memories');
html=html.replace('The eternal fire burns. Glory now flows from the Temple.','The Temple is ready. Train priests and keep them nearby to generate Glory.');
const scripts=[...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)].map(m=>m[1]);
for(const script of scripts)new vm.Script(script);
fs.writeFileSync(file,html);
console.log('Built Ariel campaign: 62 memories, '+new Set(levels.map(l=>l.act)).size+' acts. All scripts parse.');
